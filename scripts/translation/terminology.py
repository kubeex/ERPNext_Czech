def title_from_snake(s: str) -> str:
    """Convert a doctype folder name (snake_case) to its Frappe Title Case
    display name, e.g. "sales_invoice" -> "Sales Invoice"."""
    parts = s.replace("/", " ").split("_")
    small = {"and", "or", "of", "for", "the", "on", "in", "to", "a"}
    acronyms = {"BOM", "POS", "UOM", "HR", "GST", "TDS", "HRA", "ID", "PF", "ESI", "KRA", "KPI"}
    words = []
    for i, p in enumerate(parts):
        if not p:
            continue
        if p.upper() in acronyms:
            words.append(p.upper())
        elif i > 0 and p.lower() in small:
            words.append(p.lower())
        else:
            words.append(p.capitalize())
    return " ".join(words)
